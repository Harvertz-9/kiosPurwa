const locale = computed(() => state.locale)

const t = (key) => {
    const value = translations[state.locale]?.[key]
    if (value !== undefined) {
        return value
    }
    return translations.id[key] ?? key
}

const setLocale = (lang) => {
    if (translations[lang]) {
        state.locale = lang
    }
}

export function useI18n() {
    return {
        locale,
        t,
        setLocale
    }
}

export default {
    install(app) {
        app.provide('i18n', { locale, t, setLocale })
        app.config.globalProperties.$t = t
    }
}
